import fs from 'node:fs';
import ts from 'typescript';
import assert from 'node:assert/strict';
const api={};
new Function('exports',ts.transpileModule(fs.readFileSync('app/voice-place-choice.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText)(api);
const city=(id,name,state,kind='city')=>({id,name,state,kind,label:name+', '+state,detail:state,point:[-80,35]});
const charlotte=city('clt','Charlotte','North Carolina');
assert.equal(api.chooseVoicePlace('Charlotte, North Carolina',[city('poi','Charlotte','North Carolina','station'),charlotte]),'clt');
assert.equal(api.chooseVoicePlace('Charlotte, NC, USA',[charlotte]),'clt');
const dc=city('dc','Washington','District of Columbia'),wa=city('nc','Washington','North Carolina');
assert.equal(api.chooseVoicePlace('Washington, D.C.',[wa,dc]),'dc');
assert.equal(api.chooseVoicePlace('Washington',[wa,dc]),'');
assert.equal(api.chooseVoicePlace('Charlotte, South Carolina',[charlotte]),'');
assert.equal(api.chooseVoicePlace('Charlotte',[city('poi','Charlotte','North Carolina','station')]),'');
assert.equal(api.chooseVoicePlace('Charlotte',[charlotte,{...charlotte,id:'duplicate'}]),'');
assert.equal(api.chooseVoicePlace('Nashville',[]),'');
console.log('PASS: city/state match, state abbreviation, DC, ambiguous names, wrong state, POIs, duplicates, missing results');
assert.equal(api.chooseVoiceRoutePlace('Charlotte',[charlotte]),'');
assert.equal(api.chooseVoiceRoutePlace('Charlotte, NC',[charlotte]),'clt');
assert.equal(api.chooseVoiceRoutePlace('Charlotte, North Carolina',[charlotte]),'clt');
assert.equal(api.chooseVoiceRoutePlace('Charlotte, South Carolina',[charlotte]),'');
assert.equal(api.chooseVoiceRoutePlace('Washington, D.C.',[wa,dc]),'dc');
console.log('PASS: automatic voice routes require a state, including abbreviations and DC');
